use std::{env, error::Error, fmt::Write as _, fs, path::Path};
use time::{Date, Month, Time};

#[allow(
    dead_code,
    reason = "all supported schema variants need not occur in the current manifest"
)]
#[derive(Clone, Copy)]
enum XType {
    F64,
    U8,
    U16,
    U32,
    U64,
    Date,
    Time,
}

#[allow(
    dead_code,
    reason = "both response shapes need not occur in the current manifest"
)]
#[derive(Clone, Copy)]
enum YShape {
    Scalar,
    Fixed(usize),
}

#[derive(Clone, Copy)]
struct DatasetSpec {
    name: &'static str,
    path: &'static str,
    x_type: XType,
    y_shape: YShape,
}

macro_rules! x_type {
    (f64) => {
        XType::F64
    };
    (u8) => {
        XType::U8
    };
    (u16) => {
        XType::U16
    };
    (u32) => {
        XType::U32
    };
    (u64) => {
        XType::U64
    };
    (Date) => {
        XType::Date
    };
    (Time) => {
        XType::Time
    };
}

macro_rules! y_shape {
    (f64) => {
        YShape::Scalar
    };
    ([f64; $dimension:literal]) => {
        YShape::Fixed($dimension)
    };
}

macro_rules! datasets {
    (
        $(
            $name:ident {
                path: $path:literal,
                x: $x:ident,
                y: $y:tt $(,)?
            }
        )*
    ) => {
        const DATASETS: &[DatasetSpec] = &[
            $(
                DatasetSpec {
                    name: stringify!($name),
                    path: $path,
                    x_type: x_type!($x),
                    y_shape: y_shape!($y),
                },
            )*
        ];
    };
}

include!("datasets.rs");

struct ParsedDataset {
    x: Vec<String>,
    y: ResponseRows,
}

struct ResponseRows {
    values: Vec<f64>,
    width: usize,
}

impl ResponseRows {
    const fn new(width: usize) -> Self {
        Self {
            values: Vec::new(),
            width,
        }
    }

    fn push_row(
        &mut self,
        values: &[&str],
        path: &Path,
        line: usize,
    ) -> Result<(), Box<dyn Error>> {
        debug_assert_eq!(values.len(), self.width);
        for (component, value) in values.iter().enumerate() {
            self.values
                .push(parse_finite_f64(value, path, line, component + 2)?);
        }
        Ok(())
    }

    const fn len(&self) -> usize {
        self.values.len() / self.width
    }

    fn rows(&self) -> impl ExactSizeIterator<Item = &[f64]> {
        self.values.chunks_exact(self.width)
    }
}

fn main() -> Result<(), Box<dyn Error>> {
    println!("cargo::rerun-if-changed=datasets.rs");
    validate_manifest(DATASETS)?;
    let mut generated = String::from("// @generated by build.rs; do not edit.\n\n");

    for spec in DATASETS {
        println!("cargo::rerun-if-changed={}", spec.path);
        let dataset = read_csv(spec)?;
        write_dataset(&mut generated, spec, &dataset)?;
    }

    let out_dir = env::var("OUT_DIR")?;
    fs::write(Path::new(&out_dir).join("built_in_datasets.rs"), generated)?;
    Ok(())
}

fn validate_manifest(specs: &[DatasetSpec]) -> Result<(), Box<dyn Error>> {
    if specs.is_empty() {
        return Err("datasets.rs must declare at least one dataset".into());
    }
    for (index, spec) in specs.iter().enumerate() {
        if matches!(spec.y_shape, YShape::Fixed(0)) {
            return Err(format!("dataset `{}` has a zero-dimensional response", spec.name).into());
        }
        for previous in &specs[..index] {
            if spec.name.eq_ignore_ascii_case(previous.name) {
                return Err(format!(
                    "dataset names `{}` and `{}` produce colliding generated identifiers",
                    previous.name, spec.name
                )
                .into());
            }
            if spec.path == previous.path {
                return Err(format!(
                    "datasets `{}` and `{}` use the same CSV path `{}`",
                    previous.name, spec.name, spec.path
                )
                .into());
            }
        }
    }
    Ok(())
}

fn read_csv(spec: &DatasetSpec) -> Result<ParsedDataset, Box<dyn Error>> {
    let path = Path::new(spec.path);
    let contents = fs::read_to_string(path)?;
    parse_csv(spec, path, &contents)
}

fn parse_csv(
    spec: &DatasetSpec,
    path: &Path,
    contents: &str,
) -> Result<ParsedDataset, Box<dyn Error>> {
    let mut lines = contents.lines();
    let header = lines
        .next()
        .ok_or_else(|| format!("{} is empty", path.display()))?;
    let names = split_row(header, path, 1)?;
    let y_dimension = y_dimension(spec, path)?;
    let expected_columns = y_dimension.checked_add(1).ok_or_else(|| {
        format!(
            "{}: response dimension for dataset `{}` is too large",
            path.display(),
            spec.name
        )
    })?;

    if names.len() != expected_columns {
        return Err(format!(
            "{} has {} columns; schema for `{}` requires one x column and {y_dimension} y columns",
            path.display(),
            names.len(),
            spec.name,
        )
        .into());
    }
    if names[0] != "x" {
        return Err(format!("{}: first column must be named `x`", path.display()).into());
    }
    if names.iter().any(|name| name.is_empty()) {
        return Err(format!("{} has an empty column name", path.display()).into());
    }
    if names
        .iter()
        .enumerate()
        .any(|(index, name)| names[..index].contains(name))
    {
        return Err(format!("{} has duplicate column names", path.display()).into());
    }
    if names.iter().any(|name| !is_rust_identifier(name)) {
        return Err(format!("{} has a non-identifier column name", path.display()).into());
    }

    let mut x = Vec::new();
    let mut y = ResponseRows::new(y_dimension);
    for (line_index, line) in lines.enumerate() {
        let line_number = line_index + 2;
        if line.trim().is_empty() {
            return Err(format!("{}:{line_number} is empty", path.display()).into());
        }
        let values = split_row(line, path, line_number)?;
        if values.len() != expected_columns {
            return Err(format!(
                "{}:{line_number} has {} fields; expected {expected_columns}",
                path.display(),
                values.len(),
            )
            .into());
        }

        x.push(parse_x_literal(spec.x_type, values[0], path, line_number)?);
        y.push_row(&values[1..], path, line_number)?;
    }

    if y.len() == 0 {
        return Err(format!("{} has no data rows", path.display()).into());
    }
    Ok(ParsedDataset { x, y })
}

fn y_dimension(spec: &DatasetSpec, path: &Path) -> Result<usize, Box<dyn Error>> {
    match spec.y_shape {
        YShape::Scalar => Ok(1),
        YShape::Fixed(0) => Err(format!("{}: response dimension is zero", path.display()).into()),
        YShape::Fixed(dimension) => Ok(dimension),
    }
}

fn parse_x_literal(
    x_type: XType,
    value: &str,
    path: &Path,
    line_number: usize,
) -> Result<String, Box<dyn Error>> {
    match x_type {
        XType::F64 => Ok(format!(
            "{:?}",
            parse_finite_f64(value, path, line_number, 1)?
        )),
        XType::U8 => parse_integer_literal::<u8>(value, "u8", path, line_number),
        XType::U16 => parse_integer_literal::<u16>(value, "u16", path, line_number),
        XType::U32 => parse_integer_literal::<u32>(value, "u32", path, line_number),
        XType::U64 => parse_integer_literal::<u64>(value, "u64", path, line_number),
        XType::Date => Ok(date_literal(parse_date(value, path, line_number)?)),
        XType::Time => Ok(time_literal(parse_time(value, path, line_number)?)),
    }
}

fn parse_finite_f64(
    value: &str,
    path: &Path,
    line_number: usize,
    column_number: usize,
) -> Result<f64, Box<dyn Error>> {
    let parsed = value.parse::<f64>().map_err(|_| {
        format!(
            "{}:{line_number}:{column_number} is not an f64",
            path.display()
        )
    })?;
    if !parsed.is_finite() {
        return Err(format!(
            "{}:{line_number}:{column_number} is not finite",
            path.display()
        )
        .into());
    }
    Ok(parsed)
}

fn parse_integer_literal<T>(
    value: &str,
    type_name: &str,
    path: &Path,
    line_number: usize,
) -> Result<String, Box<dyn Error>>
where
    T: std::fmt::Display + std::str::FromStr,
{
    let parsed = value
        .parse::<T>()
        .map_err(|_| format!("{}:{line_number}:1 is not a {type_name}", path.display()))?;
    Ok(parsed.to_string())
}

fn parse_date(value: &str, path: &Path, line_number: usize) -> Result<Date, Box<dyn Error>> {
    let invalid = || invalid_x(path, line_number, "date in YYYY-MM-DD format");
    let bytes = value.as_bytes();
    if bytes.len() != 10 || bytes[4] != b'-' || bytes[7] != b'-' {
        return Err(invalid().into());
    }
    let year = value[..4].parse::<i32>().map_err(|_| invalid())?;
    let month_number = value[5..7].parse::<u8>().map_err(|_| invalid())?;
    let day = value[8..].parse::<u8>().map_err(|_| invalid())?;
    let month = Month::try_from(month_number).map_err(|_| invalid())?;
    Date::from_calendar_date(year, month, day).map_err(|_| invalid().into())
}

fn parse_time(value: &str, path: &Path, line_number: usize) -> Result<Time, Box<dyn Error>> {
    let invalid = || invalid_x(path, line_number, "time in HH:MM:SS[.fraction] format");
    let mut parts = value.split(':');
    let hour_text = parts.next().ok_or_else(invalid)?;
    let minute_text = parts.next().ok_or_else(invalid)?;
    let seconds = parts.next().ok_or_else(invalid)?;
    if parts.next().is_some() || hour_text.len() != 2 || minute_text.len() != 2 {
        return Err(invalid().into());
    }
    let hour = hour_text.parse::<u8>().map_err(|_| invalid())?;
    let minute = minute_text.parse::<u8>().map_err(|_| invalid())?;
    let (second, nanosecond) = parse_seconds(seconds).ok_or_else(invalid)?;
    Time::from_hms_nano(hour, minute, second, nanosecond).map_err(|_| invalid().into())
}

fn date_literal(value: Date) -> String {
    let (year, month, day) = value.to_calendar_date();
    format!("time::macros::date!({year} - {} - {day})", u8::from(month))
}

fn time_literal(value: Time) -> String {
    if value.nanosecond() == 0 {
        format!(
            "time::macros::time!({}:{}:{})",
            value.hour(),
            value.minute(),
            value.second()
        )
    } else {
        format!(
            "time::macros::time!({}:{}:{}.{:09})",
            value.hour(),
            value.minute(),
            value.second(),
            value.nanosecond()
        )
    }
}

fn parse_seconds(value: &str) -> Option<(u8, u32)> {
    let (seconds, fraction) = value
        .split_once('.')
        .map_or((value, None), |(seconds, fraction)| {
            (seconds, Some(fraction))
        });
    if seconds.len() != 2 {
        return None;
    }
    let second = seconds.parse::<u8>().ok()?;
    let nanosecond = match fraction {
        None => 0,
        Some(fraction)
            if !fraction.is_empty()
                && fraction.len() <= 9
                && fraction.bytes().all(|byte| byte.is_ascii_digit()) =>
        {
            let digits = fraction.parse::<u32>().ok()?;
            digits * 10_u32.pow(9_u32 - u32::try_from(fraction.len()).ok()?)
        }
        Some(_) => return None,
    };
    Some((second, nanosecond))
}

fn invalid_x(path: &Path, line_number: usize, expected: &str) -> String {
    format!(
        "{}:{line_number}:1 is not a valid {expected}",
        path.display()
    )
}

fn split_row<'a>(
    line: &'a str,
    path: &Path,
    line_number: usize,
) -> Result<Vec<&'a str>, Box<dyn Error>> {
    if line.contains('"') {
        return Err(format!(
            "{}:{line_number} contains unsupported CSV quoting",
            path.display()
        )
        .into());
    }
    Ok(line.split(',').map(str::trim).collect())
}

fn is_rust_identifier(name: &str) -> bool {
    let mut characters = name.chars();
    matches!(characters.next(), Some('a'..='z' | 'A'..='Z' | '_'))
        && characters.all(|character| character.is_ascii_alphanumeric() || character == '_')
}

fn write_dataset(
    output: &mut String,
    spec: &DatasetSpec,
    dataset: &ParsedDataset,
) -> Result<(), std::fmt::Error> {
    let constant_name = spec.name.to_ascii_uppercase();
    write_x(output, &constant_name, spec.x_type, &dataset.x)?;
    write_y(output, &constant_name, spec.y_shape, &dataset.y)?;
    write_accessor(output, spec, &constant_name, dataset.y.len())
}

fn write_x(
    output: &mut String,
    name: &str,
    x_type: XType,
    values: &[String],
) -> Result<(), std::fmt::Error> {
    let type_name = rust_x_type(x_type);
    writeln!(
        output,
        "static {name}_X: [{type_name}; {}] = [",
        values.len()
    )?;
    for value in values {
        writeln!(output, "    {value},")?;
    }
    writeln!(output, "];\n")
}

fn write_y(
    output: &mut String,
    name: &str,
    shape: YShape,
    responses: &ResponseRows,
) -> Result<(), std::fmt::Error> {
    match shape {
        YShape::Scalar => {
            writeln!(output, "static {name}_Y: [f64; {}] = [", responses.len())?;
            for value in &responses.values {
                writeln!(output, "    {value:?},")?;
            }
        }
        YShape::Fixed(dimension) => {
            debug_assert_eq!(responses.width, dimension);
            writeln!(
                output,
                "static {name}_Y: [[f64; {dimension}]; {}] = [",
                responses.len()
            )?;
            for row in responses.rows() {
                write!(output, "    [")?;
                for value in row {
                    write!(output, "{value:?}, ")?;
                }
                writeln!(output, "],")?;
            }
        }
    }
    writeln!(output, "];\n")
}

fn write_accessor(
    output: &mut String,
    spec: &DatasetSpec,
    constant_name: &str,
    observations: usize,
) -> Result<(), std::fmt::Error> {
    let x_type = rust_x_type(spec.x_type);
    let y_type = match spec.y_shape {
        YShape::Scalar => "&'static [f64]".to_owned(),
        YShape::Fixed(dimension) => format!("&'static [[f64; {dimension}]]"),
    };
    writeln!(output, "/// Returns the `{}` built-in dataset.", spec.name)?;
    writeln!(output, "///")?;
    writeln!(
        output,
        "/// The dataset contains {observations} aligned observations."
    )?;
    writeln!(output, "#[must_use]")?;
    writeln!(
        output,
        "pub const fn {}() -> crate::Dataset<&'static [{x_type}], {y_type}> {{",
        spec.name
    )?;
    writeln!(
        output,
        "    crate::Dataset::new(&{constant_name}_X, &{constant_name}_Y)"
    )?;
    writeln!(output, "}}\n")
}

const fn rust_x_type(x_type: XType) -> &'static str {
    match x_type {
        XType::F64 => "f64",
        XType::U8 => "u8",
        XType::U16 => "u16",
        XType::U32 => "u32",
        XType::U64 => "u64",
        XType::Date => "crate::Date",
        XType::Time => "crate::Time",
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const TEST_PATH: &str = "data/test.csv";

    const fn spec(name: &'static str, x_type: XType, y_shape: YShape) -> DatasetSpec {
        DatasetSpec {
            name,
            path: TEST_PATH,
            x_type,
            y_shape,
        }
    }

    #[test]
    fn scalar_unsigned_schema_parses_and_generates_typed_accessor() {
        let spec = spec("counts", XType::U64, YShape::Scalar);
        let parsed = parse_csv(
            &spec,
            Path::new(TEST_PATH),
            "x,y\n0,1.5\n18446744073709551615,2.5\n",
        )
        .unwrap();
        assert_eq!(parsed.x, ["0", "18446744073709551615"]);
        assert_eq!(parsed.y.values, [1.5, 2.5]);

        let mut generated = String::new();
        write_dataset(&mut generated, &spec, &parsed).unwrap();
        assert!(
            generated.contains(
                "pub const fn counts() -> crate::Dataset<&'static [u64], &'static [f64]>"
            )
        );
    }

    #[test]
    fn date_and_time_schemas_generate_fixed_width_rows() {
        let date_spec = spec("dated", XType::Date, YShape::Fixed(2));
        let dated = parse_csv(
            &date_spec,
            Path::new(TEST_PATH),
            "x,y0,y1\n2024-02-29,1.0,2.0\n2025-03-01,3.0,4.0\n",
        )
        .unwrap();
        assert_eq!(dated.y.rows().collect::<Vec<_>>(), [[1.0, 2.0], [3.0, 4.0]]);

        let time_spec = spec("timed", XType::Time, YShape::Fixed(3));
        let timed = parse_csv(
            &time_spec,
            Path::new(TEST_PATH),
            "x,y0,y1,y2\n09:30:00.125,1.0,2.0,3.0\n23:59:59.000000001,4.0,5.0,6.0\n",
        )
        .unwrap();

        let mut generated = String::new();
        write_dataset(&mut generated, &date_spec, &dated).unwrap();
        write_dataset(&mut generated, &time_spec, &timed).unwrap();
        assert!(generated.contains("time::macros::date!(2024 - 2 - 29)"));
        assert!(generated.contains("time::macros::time!(9:30:0.125000000)"));
        assert!(generated.contains("&'static [[f64; 3]]"));
    }

    #[test]
    fn parser_rejects_noncanonical_temporal_values_and_wrong_shape() {
        let date_spec = spec("dated", XType::Date, YShape::Scalar);
        assert!(parse_csv(&date_spec, Path::new(TEST_PATH), "x,y\n2024-2-29,1.0\n").is_err());

        let time_spec = spec("timed", XType::Time, YShape::Scalar);
        assert!(parse_csv(&time_spec, Path::new(TEST_PATH), "x,y\n9:30:00,1.0\n").is_err());

        let vector_spec = spec("vector", XType::F64, YShape::Fixed(2));
        assert!(parse_csv(&vector_spec, Path::new(TEST_PATH), "x,y\n1.0,2.0\n").is_err());
    }

    #[test]
    fn manifest_rejects_generated_identifier_collisions() {
        let specs = [
            spec("sample", XType::F64, YShape::Scalar),
            DatasetSpec {
                name: "SAMPLE",
                path: "data/other.csv",
                x_type: XType::F64,
                y_shape: YShape::Scalar,
            },
        ];
        assert!(validate_manifest(&specs).is_err());
    }
}
