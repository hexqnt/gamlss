use std::{env, error::Error, fmt::Write as _, fs, path::Path};

const DATASETS: &[(&str, &str)] = &[("a1", "data/a1.csv")];

type NumericColumns = Vec<(String, Vec<f64>)>;

fn main() -> Result<(), Box<dyn Error>> {
    let mut generated = String::from("// @generated by build.rs; do not edit.\n");

    for &(name, path) in DATASETS {
        println!("cargo::rerun-if-changed={path}");
        let columns = read_csv(Path::new(path))?;
        write_dataset(&mut generated, name, &columns)?;
    }

    let out_dir = env::var("OUT_DIR")?;
    fs::write(Path::new(&out_dir).join("built_in_datasets.rs"), generated)?;
    Ok(())
}

fn read_csv(path: &Path) -> Result<NumericColumns, Box<dyn Error>> {
    let contents = fs::read_to_string(path)?;
    let mut lines = contents.lines();
    let header = lines
        .next()
        .ok_or_else(|| format!("{} is empty", path.display()))?;
    let names = split_row(header, path, 1)?;

    if names.is_empty() || names.iter().any(|name| name.is_empty()) {
        return Err(format!("{} has an empty column name", path.display()).into());
    }
    if names
        .iter()
        .enumerate()
        .any(|(index, name)| names[..index].contains(name))
    {
        return Err(format!("{} has duplicate column names", path.display()).into());
    }
    if names.iter().any(|name| !is_rust_identifier(name)) {
        return Err(format!("{} has a non-identifier column name", path.display()).into());
    }

    let mut columns = names
        .into_iter()
        .map(|name| (name.to_owned(), Vec::new()))
        .collect::<Vec<_>>();

    for (line_index, line) in lines.enumerate() {
        let line_number = line_index + 2;
        if line.trim().is_empty() {
            return Err(format!("{}:{line_number} is empty", path.display()).into());
        }
        let values = split_row(line, path, line_number)?;
        if values.len() != columns.len() {
            return Err(format!(
                "{}:{line_number} has {} fields; expected {}",
                path.display(),
                values.len(),
                columns.len()
            )
            .into());
        }

        for (column_index, value) in values.iter().enumerate() {
            let parsed = value.parse::<f64>().map_err(|_| {
                format!(
                    "{}:{line_number}:{} is not an f64",
                    path.display(),
                    column_index + 1
                )
            })?;
            if !parsed.is_finite() {
                return Err(format!(
                    "{}:{line_number}:{} is not finite",
                    path.display(),
                    column_index + 1
                )
                .into());
            }
            columns[column_index].1.push(parsed);
        }
    }

    if columns.first().is_none_or(|(_, values)| values.is_empty()) {
        return Err(format!("{} has no data rows", path.display()).into());
    }
    Ok(columns)
}

fn split_row<'a>(
    line: &'a str,
    path: &Path,
    line_number: usize,
) -> Result<Vec<&'a str>, Box<dyn Error>> {
    if line.contains('"') {
        return Err(format!(
            "{}:{line_number} contains unsupported CSV quoting",
            path.display()
        )
        .into());
    }
    Ok(line.split(',').map(str::trim).collect())
}

fn is_rust_identifier(name: &str) -> bool {
    let mut characters = name.chars();
    matches!(characters.next(), Some('a'..='z' | 'A'..='Z' | '_'))
        && characters.all(|character| character.is_ascii_alphanumeric() || character == '_')
}

fn write_dataset(
    output: &mut String,
    dataset_name: &str,
    columns: &NumericColumns,
) -> Result<(), std::fmt::Error> {
    let dataset_name = dataset_name.to_ascii_uppercase();
    for (column_name, values) in columns {
        let column_name = column_name.to_ascii_uppercase();
        writeln!(
            output,
            "pub static {dataset_name}_{column_name}: [f64; {}] = [",
            values.len()
        )?;
        for value in values {
            writeln!(output, "    {value:?},")?;
        }
        writeln!(output, "];\n")?;
    }
    Ok(())
}
